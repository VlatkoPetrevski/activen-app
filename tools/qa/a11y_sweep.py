import os
import asyncio, json, sys
from playwright.async_api import async_playwright
AXE=open(os.environ.get("AXE_JS", "node_modules/axe-core/axe.min.js")).read()
results=[]
async def check(pg, name):
    await pg.wait_for_timeout(700)
    over = await pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
    await pg.add_script_tag(content=AXE)
    v = await pg.evaluate("""async () => { const r = await axe.run(document, {runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa']}});
      return r.violations.map(v => ({id:v.id, impact:v.impact, n:v.nodes.length, sample:v.nodes.slice(0,2).map(n=>n.target.join(' ')+' :: '+(n.failureSummary||'').split('\\n')[1])})) }""")
    results.append({"screen":name,"overflow":over,"axe":v})
async def run(width):
    async with async_playwright() as p:
        b = await p.chromium.launch(args=["--no-sandbox"])
        pg = await b.new_page(viewport={"width":width,"height":900}, locale="mk-MK")
        errors=[]
        pg.on("pageerror", lambda e: errors.append(("pageerror", str(e))))
        pg.on("console", lambda m: m.type=="error" and errors.append(("console", m.text)))
        await pg.goto(os.environ.get("BASE", "http://localhost:4173/index.html")); await pg.wait_for_timeout(800)
        await check(pg, f"{width} sign-in")
        await pg.get_by_role("button", name="Пробај како спортист").click(); await pg.wait_for_timeout(1500)
        await check(pg, f"{width} today")
        await pg.get_by_role("button", name="Внеси сон").last.click(); await check(pg, f"{width} today-morning-input")
        nav = lambda n: pg.get_by_role("link", name=n).last.click()
        await nav("План"); await check(pg, f"{width} plan")
        await nav("Активности"); await check(pg, f"{width} activities")
        await pg.get_by_role("button", name="Страница 2").click(); await check(pg, f"{width} activities-page2")
        await pg.get_by_role("button", name="Внеси рачно").click(); await check(pg, f"{width} activities-manual")
        await pg.keyboard.press("Escape")
        await pg.get_by_role("button", name="Увези", exact=True).click(); await check(pg, f"{width} activities-import-panel")
        fit = os.environ.get("SAMPLE_FIT")
        if fit:
            await pg.locator("[data-testid=import-input]").first.set_input_files(fit)
            await pg.get_by_text("1 увезена").wait_for(); await check(pg, f"{width} activities-import")
        await pg.locator(".activity-line").nth(1).click(); await check(pg, f"{width} activity")
        await pg.get_by_role("tab", name="Детали").click(); await check(pg, f"{width} activity-details")
        await pg.get_by_role("tab", name="Оценка").click(); await check(pg, f"{width} activity-rating")
        await pg.get_by_role("tab", name="Преглед").click()
        await pg.get_by_role("link", name="Сподели").click(); await check(pg, f"{width} share")
        await nav("Напредок"); await check(pg, f"{width} progress")
        await nav("Тренер"); await check(pg, f"{width} my-coach")
        await pg.get_by_role("button", name="Поставки").click(); await check(pg, f"{width} my-coach-settings")
        await pg.keyboard.press("Escape")
        await pg.get_by_role("link", name="Профил").last.click(); await check(pg, f"{width} profile")
        await pg.get_by_role("button", name="Извори на податоци").click(); await check(pg, f"{width} profile-sources")
        await pg.get_by_role("button", name="Известувања").click(); await check(pg, f"{width} profile-notifications")
        results.append({"screen":f"{width} athlete errors","errors":list(errors)})
        errors.clear()
        pg = await b.new_page(viewport={"width":width,"height":900}, locale="mk-MK")
        pg.on("pageerror", lambda e: errors.append(("pageerror", str(e))))
        pg.on("console", lambda m: m.type=="error" and errors.append(("console", m.text)))
        nav = lambda n: pg.get_by_role("link", name=n).last.click()
        await pg.goto(os.environ.get("BASE", "http://localhost:4173/index.html")); await pg.wait_for_timeout(800)
        await pg.get_by_role("button", name="Пробај како тренер").click(); await pg.wait_for_timeout(1500)
        await check(pg, f"{width} coach-athletes")
        if width <= 720:
            # Phones: section menu, athlete cards, tabs, list → conversation.
            async def section(name):
                await pg.locator(".section-menu-button").click(); await check(pg, f"{width} coach-menu-{name}")
                await pg.locator(".section-menu-list").get_by_role("link", name=name).click(); await pg.wait_for_timeout(600)
            await pg.locator(".athlete-card").first.click(); await check(pg, f"{width} coach-athlete")
            for tab in ("Пораки", "Напредок"):
                await pg.get_by_role("tab", name=tab).click(); await check(pg, f"{width} coach-athlete-{tab}")
            await section("Анализи"); await check(pg, f"{width} analytics")
            await section("Планер"); await check(pg, f"{width} planner")
            await pg.get_by_role("button", name="Додај тренинг", exact=True).click(); await check(pg, f"{width} plan-editor")
            await pg.keyboard.press("Escape")
            await pg.get_by_role("button", name="Внеси план", exact=True).click(); await check(pg, f"{width} plan-import")
            await pg.keyboard.press("Escape")
            await section("Пораки"); await check(pg, f"{width} messages")
            await pg.locator(".list-item").first.click(); await check(pg, f"{width} messages-thread")
        else:
            await pg.locator(".segment-head").first.click(); await check(pg, f"{width} coach-athletes-open")
            await pg.locator(".segment.open").get_by_role("link", name="Профил").click(); await check(pg, f"{width} coach-athlete")
            await pg.get_by_role("link", name="Спортисти").first.click(); await pg.wait_for_timeout(500)
            await pg.get_by_role("link", name="Анализи").first.click(); await check(pg, f"{width} analytics")
            await pg.locator(".segment-head").first.click(); await pg.locator(".segment .btn-primary").first.click(); await check(pg, f"{width} analytics-athlete")
            await pg.locator(".an-activity").first.click(); await check(pg, f"{width} analytics-activity")
            await pg.get_by_role("link", name="Планер").first.click(); await check(pg, f"{width} planner")
            # Early in the week nothing is done yet: the previous week has activities.
            if await pg.locator(".cmp-done").count() == 0:
                await pg.get_by_role("button", name="Претходна недела").first.click(); await pg.wait_for_timeout(500)
            await pg.locator(".cmp-done").first.click(); await check(pg, f"{width} planner-stats")
            await pg.keyboard.press("Escape")
            await pg.get_by_role("button", name="Додај тренинг", exact=True).click(); await check(pg, f"{width} plan-editor")
            await pg.keyboard.press("Escape")
            await pg.get_by_role("button", name="Внеси план", exact=True).click(); await check(pg, f"{width} plan-import")
            await pg.keyboard.press("Escape")
            await pg.get_by_role("link", name="Пораки").first.click(); await check(pg, f"{width} messages")
        results.append({"screen":f"{width} coach errors","errors":errors})
        json.dump(results, open(os.environ.get("OUT", "a11y-report.json"),"w"), ensure_ascii=False, indent=1)
        await b.close()
async def main():
    for w in (390, 1280): await run(w)
    json.dump(results, open(os.environ.get("OUT", "a11y-report.json"),"w"), ensure_ascii=False, indent=1)
asyncio.run(main())
